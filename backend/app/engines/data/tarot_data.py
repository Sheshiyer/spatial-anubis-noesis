def get_card_by_id(card_id: int) -> Dict:
    """Get card data by ID (0-77)."""
    return TAROT_CARDS.get(card_id, {})


def get_cards_by_suit(suit: str) -> List[Dict]:
    """Get all cards of a specific suit."""
    return [card for card in TAROT_CARDS.values() if card.get("suit") == suit]


def get_major_arcana() -> List[Dict]:
    """Get all Major Arcana cards (0-21)."""
    return [card for card in TAROT_CARDS.values() if card["arcana"] == "major"]
