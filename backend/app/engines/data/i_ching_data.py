def get_transformed_hexagram(hexagram_number: int, changing_lines: List[int]) -> int:
    """Calculate transformed hexagram by flipping changing lines."""
    binary = hexagram_number - 1
    for line in changing_lines:
        if 1 <= line <= 6:
            bit_position = line - 1
            binary ^= (1 << bit_position)
    return binary + 1


