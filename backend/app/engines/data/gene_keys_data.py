def calculate_spheres(birth_date_str: str) -> Dict[str, int]:
    """
    Calculate the four primary spheres from birth date.
    Returns Life's Work, Evolution, Radiance, and Purpose keys.
    """
    # Simplified calculation - in production, use proper Gene Keys algorithm
    import hashlib
    
    # Create deterministic numbers from birth date
    hash_val = int(hashlib.md5(birth_date_str.encode()).hexdigest(), 16)
    
    spheres = {
        "lifes_work": (hash_val % 64) + 1,
        "evolution": ((hash_val >> 8) % 64) + 1,
        "radiance": ((hash_val >> 16) % 64) + 1,
        "purpose": ((hash_val >> 24) % 64) + 1,
    }
    
    return spheres
